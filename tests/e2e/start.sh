#!/usr/bin/env bash
# Boot Fiber's local CKB + three fnn nodes, open Twine channels, write .env.
set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)"
twine_root="$(cd -- "$script_dir/../.." &>/dev/null && pwd)"
fiber_repo="${FIBER_REPO:-$twine_root/../fiber}"
pid_file="$script_dir/fiber-start.pid"
log_file="$script_dir/fiber-nodes.log"
env_file="$script_dir/.env"
# Local Fiber RPC has no biscuit; HttpFiber still needs a non-empty Bearer.
rpc_token="${TWINE_E2E_RPC_TOKEN:-e2e}"

HUB_RPC="${HUB_RPC:-http://127.0.0.1:21714}"
SELLER_RPC="${SELLER_RPC:-http://127.0.0.1:21715}"
BUYER_RPC="${BUYER_RPC:-http://127.0.0.1:21716}"

die() {
  echo "$*" >&2
  exit 1
}

require_cmd() {
  command -v "$1" >/dev/null || die "$1 is required for Twine e2e"
}

resolve_fiber_repo() {
  [[ -d "$fiber_repo" ]] || die "FIBER_REPO not found at $fiber_repo (clone nervosnetwork/fiber and check out v0.9.1)"
  fiber_repo="$(cd -- "$fiber_repo" &>/dev/null && pwd)"
  [[ -x "$fiber_repo/tests/nodes/start.sh" ]] || die "FIBER_REPO does not look like a Fiber checkout: $fiber_repo"
  local tag
  tag=$(git -C "$fiber_repo" describe --tags --exact-match 2>/dev/null || true)
  if [[ "$tag" != "v0.9.1" ]]; then
    echo "warning: Twine pins Fiber 0.9.1; FIBER_REPO is currently '${tag:-detached/branch}'" >&2
    echo "warning: run: git -C \"$fiber_repo\" checkout v0.9.1" >&2
  fi
}

write_env() {
  umask 077
  cat >"$env_file" <<EOF
# Generated by tests/e2e/start.sh. Do not commit.
FIBER_NETWORK=dev
TWINE_RPC=$HUB_RPC
TWINE_RPC_TOKEN=$rpc_token
TWINE_E2E_SELLER_RPC=$SELLER_RPC
TWINE_E2E_SELLER_TOKEN=$rpc_token
TWINE_E2E_BUYER_RPC=$BUYER_RPC
TWINE_E2E_BUYER_TOKEN=$rpc_token
FIBER_REPO=$fiber_repo
EOF
  echo "wrote $env_file"
}

main() {
  require_cmd curl
  require_cmd python3
  require_cmd ckb
  require_cmd ckb-cli
  require_cmd cargo
  require_cmd git
  resolve_fiber_repo

  echo "stopping any previous e2e stack ..."
  "$script_dir/stop.sh" || true

  echo "starting Fiber nodes from $fiber_repo ..."
  (
    cd "$fiber_repo"
    # node1=hub, node2=seller, node3=buyer
    REMOVE_OLD_STATE=y ./tests/nodes/start.sh e2e/3-nodes-transfer
  ) >"$log_file" 2>&1 &
  echo $! >"$pid_file"
  echo "Fiber start.sh pid $(cat "$pid_file"); logging to $log_file"

  echo "waiting for Fiber RPC ports ..."
  (
    cd "$fiber_repo"
    ./tests/nodes/wait.sh
  )

  export HUB_RPC SELLER_RPC BUYER_RPC
  "$script_dir/setup-channels.sh"
  write_env
  echo "e2e stack is up. Source $env_file then: cargo test -- --ignored"
}

main "$@"
